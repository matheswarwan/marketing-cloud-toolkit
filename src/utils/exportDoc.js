// Exports for the result screens (from SFMC Automation Viewer's downloadFormats.js).
// A screen builds one document and this module turns it into Markdown, HTML or Word:
//
// { title, blocks: [
//   { type: 'h', level: 1-4, text },
//   { type: 'p', text },
//   { type: 'kv', rows: [[label, value], ...] },        two-column details
//   { type: 'table', columns: [label, ...], rows: [[cell, ...], ...] },
//   { type: 'code', text, lang? },
//   { type: 'svg', svg, note? },                         a drawing (HTML and PDF; the others say so)
// ] }
//
// Excel exports use sheets: [{ name, columns, rows }].

const APP = 'Marketing Cloud Toolkit'

const str = (v) => (v == null ? '' : String(v))

export function htmlEscape(s) {
  return str(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;')
}

export function safeFileName(s) {
  return str(s).replace(/[\\/:*?"<>|\s]+/g, '_').slice(0, 80) || 'export'
}

function footer(now) {
  return `Generated by ${APP} · ${now.toLocaleString()}`
}

// ── Markdown ───────────────────────────────────────────────
function mdCell(v) {
  return str(v).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>')
}

function mdTable(columns, rows) {
  const width = Math.max(columns.length, ...rows.map((r) => r.length))
  const pad = (r) => Array.from({ length: width }, (_, i) => mdCell(r[i]))
  const head = columns.length ? columns : Array(width).fill('')
  return [`| ${pad(head).join(' | ')} |`, `| ${Array(width).fill('---').join(' | ')} |`, ...rows.map((r) => `| ${pad(r).join(' | ')} |`)].join('\n')
}

export function toMarkdown(doc, now = new Date()) {
  const out = [`# ${doc.title}`]
  for (const b of doc.blocks || []) {
    if (b.type === 'h') out.push(`${'#'.repeat(Math.min(Math.max((b.level || 2) + 0, 1), 6))} ${b.text}`)
    else if (b.type === 'p') out.push(str(b.text))
    else if (b.type === 'kv') out.push(mdTable(['Property', 'Value'], b.rows || []))
    else if (b.type === 'table') out.push((b.rows || []).length ? mdTable(b.columns || [], b.rows) : '_None._')
    else if (b.type === 'code') {
      const fence = str(b.text).includes('```') ? '~~~' : '```'
      out.push(`${fence}${b.lang || ''}\n${str(b.text)}\n${fence}`)
    } else if (b.type === 'svg') out.push(`_${str(b.note || 'Diagram: in the HTML and PDF downloads.')}_`)
  }
  out.push(`*${footer(now)}*`)
  return out.join('\n\n') + '\n'
}

// ── HTML ───────────────────────────────────────────────────
function htmlTable(columns, rows) {
  const head = columns.length ? `<thead><tr>${columns.map((c) => `<th>${htmlEscape(c)}</th>`).join('')}</tr></thead>` : ''
  const body = rows.map((r) => `<tr>${r.map((c) => `<td>${htmlEscape(c)}</td>`).join('')}</tr>`).join('')
  return `<table>${head}<tbody>${body}</tbody></table>`
}

export function toHtml(doc, now = new Date()) {
  const parts = []
  for (const b of doc.blocks || []) {
    if (b.type === 'h') { const l = Math.min(Math.max(b.level || 2, 2), 6); parts.push(`<h${l}>${htmlEscape(b.text)}</h${l}>`) }
    else if (b.type === 'p') parts.push(`<p>${htmlEscape(b.text)}</p>`)
    else if (b.type === 'kv') parts.push(htmlTable([], b.rows || []).replace('<table>', '<table class="kv">'))
    else if (b.type === 'table') parts.push((b.rows || []).length ? htmlTable(b.columns || [], b.rows) : '<p class="none">None.</p>')
    else if (b.type === 'code') parts.push(`<pre>${htmlEscape(b.text)}</pre>`)
    else if (b.type === 'svg') parts.push(`<div class="diagram">${b.svg}</div>`) // built by our own code, values escaped there
  }
  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><title>${htmlEscape(doc.title)}</title>
<style>
body{font-family:'Segoe UI',Arial,sans-serif;font-size:13px;color:#1a1a1a;margin:0;padding:40px 48px;max-width:1100px}
h1{font-size:22px;color:#1296CA;border-left:5px solid #1296CA;padding:10px 16px;background:#f7fbff}
h2{font-size:17px;margin-top:28px}h3{font-size:14px}
table{width:100%;border-collapse:collapse;font-size:12px;margin:10px 0 20px}
td,th{padding:6px 10px;border:1px solid #e4e8ec;vertical-align:top;text-align:left}
th,table.kv td:first-child{background:#f0f4f8;font-weight:600}
table.kv td:first-child{width:220px}
pre{background:#1e1e2e;color:#cdd6f4;padding:12px;border-radius:6px;font-family:Consolas,'Courier New',monospace;font-size:12px;white-space:pre-wrap;word-break:break-word}
.diagram{overflow:auto;border:1px solid #e4e8ec;border-radius:6px;padding:8px;margin:10px 0 20px;background:#fafbfc}
@media print{.diagram{overflow:visible}.diagram svg{width:100%;height:auto}}
.none{color:#888}.footer{margin-top:40px;border-top:1px solid #e4e8ec;padding-top:12px;font-size:11px;color:#999}
</style></head><body>
<h1>${htmlEscape(doc.title)}</h1>
${parts.join('\n')}
<div class="footer">${htmlEscape(footer(now))}</div>
</body></html>
`
}

// ── Word (.docx) ───────────────────────────────────────────
function xmlEsc(s) {
  return str(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
    // Characters XML 1.0 does not allow.
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')
}

function wRuns(text, o = {}) {
  const rpr = '<w:rPr>' + (o.bold ? '<w:b/>' : '') + (o.color ? `<w:color w:val="${o.color}"/>` : '') +
    (o.size ? `<w:sz w:val="${o.size}"/>` : '') + (o.mono ? '<w:rFonts w:ascii="Consolas" w:hAnsi="Consolas"/>' : '') + '</w:rPr>'
  return str(text).split('\n').map((line, i) => `<w:r>${rpr}${i ? '<w:br/>' : ''}<w:t xml:space="preserve">${xmlEsc(line)}</w:t></w:r>`).join('')
}
const wPara = (text, o) => `<w:p>${wRuns(text, o)}</w:p>`

function wTable(columns, rows) {
  const borders = ['top', 'left', 'bottom', 'right', 'insideH', 'insideV']
    .map((s) => `<w:${s} w:val="single" w:sz="4" w:space="0" w:color="D0D7DE"/>`).join('')
  const cell = (v, head) => `<w:tc><w:tcPr><w:tcW w:w="0" w:type="auto"/>${head ? '<w:shd w:val="clear" w:color="auto" w:fill="F0F4F8"/>' : ''}</w:tcPr>${wPara(v, { bold: head })}</w:tc>`
  const all = [...(columns.length ? [{ head: true, cells: columns }] : []), ...rows.map((r) => ({ head: false, cells: r }))]
  return `<w:tbl><w:tblPr><w:tblW w:w="0" w:type="auto"/><w:tblBorders>${borders}</w:tblBorders></w:tblPr>` +
    all.map((r) => `<w:tr>${r.cells.map((c) => cell(c, r.head)).join('')}</w:tr>`).join('') + '</w:tbl><w:p/>'
}

export function toDocxDocumentXml(doc, now = new Date()) {
  let body = wPara(doc.title, { bold: true, size: 36, color: '1296CA' })
  for (const b of doc.blocks || []) {
    if (b.type === 'h') body += wPara(b.text, { bold: true, size: (b.level || 2) <= 2 ? 28 : 24, color: '1296CA' })
    else if (b.type === 'p') body += wPara(b.text)
    else if (b.type === 'kv') body += wTable([], (b.rows || []).map(([k, v]) => [k, v]))
    else if (b.type === 'table') body += (b.rows || []).length ? wTable(b.columns || [], b.rows) : wPara('None.')
    else if (b.type === 'code') body += wPara(b.text, { mono: true, size: 18 })
    else if (b.type === 'svg') body += wPara(b.note || 'Diagram: in the HTML and PDF downloads.', { color: '666666' })
  }
  body += wPara(footer(now), { size: 16, color: '999999' })
  return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>' + body +
    '<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr>' +
    '</w:body></w:document>'
}

const CONTENT_TYPES = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>'
const RELS = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>'

export async function toDocxBlob(doc) {
  const { default: JSZip } = await import('jszip')
  const zip = new JSZip()
  zip.file('[Content_Types].xml', CONTENT_TYPES)
  zip.folder('_rels').file('.rels', RELS)
  zip.folder('word').file('document.xml', toDocxDocumentXml(doc))
  return zip.generateAsync({ type: 'blob', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' })
}

// ── Excel ──────────────────────────────────────────────────
// Sheet names: at most 31 characters, none of : \ / ? * [ ], unique.
export function uniqueSheetNames(names) {
  const used = new Set()
  return names.map((raw) => {
    let name = str(raw).replace(/[:\\/?*[\]]/g, '_').slice(0, 31) || 'Sheet'
    if (used.has(name.toLowerCase())) {
      const base = name.slice(0, 27)
      let n = 2
      while (used.has(`${base}(${n})`.toLowerCase())) n++
      name = `${base}(${n})`
    }
    used.add(name.toLowerCase())
    return name
  })
}

export async function downloadWorkbook(sheets, fileName) {
  const XLSX = await import('xlsx')
  const wb = XLSX.utils.book_new()
  const names = uniqueSheetNames(sheets.map((s) => s.name))
  sheets.forEach((s, i) => XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([s.columns, ...s.rows]), names[i]))
  XLSX.writeFile(wb, fileName)
}

export function saveBlob(blob, fileName) {
  const a = document.createElement('a')
  a.href = URL.createObjectURL(blob)
  a.download = fileName
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(a.href), 1000)
}

/** Opens the browser's print dialog on the document's HTML (choose "Save as PDF"). */
export function printDoc(doc) {
  const frame = document.createElement('iframe')
  frame.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0'
  frame.srcdoc = toHtml(doc)
  frame.onload = () => {
    frame.contentWindow.focus()
    frame.contentWindow.print()
    setTimeout(() => frame.remove(), 60000)
  }
  document.body.appendChild(frame)
}
